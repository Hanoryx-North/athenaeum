#!/usr/bin/env python3
"""Derive a standalone CLI build from the pinned runtime's production dependencies.

Cargo otherwise resolves every upstream workspace program, including V8-host experiments
that are not dependencies of the coding CLI. No implementation is stubbed or replaced.
"""
from pathlib import Path
import os
import re

root = Path(__file__).resolve().parent
source = root / "codex" / "codex-rs"
native = root / "native-cli"


def paths(text, origin):
    def relative(match):
        path = (origin / match[1]).resolve()
        return 'path = "' + Path(os.path.relpath(path, native)).as_posix() + '"'
    return re.sub(r'path\s*=\s*"([^"]+)"', relative, text)


workspace = (source / "Cargo.toml").read_text(encoding="utf-8")
cli = (source / "cli" / "Cargo.toml").read_text(encoding="utf-8")
dependencies = paths(cli[cli.index("[dependencies]"):cli.index("[dev-dependencies]")], source / "cli")
dependencies = dependencies.replace(
    "[dependencies]\n", '[dependencies]\ncodex-cli = { path = "../codex/codex-rs/cli" }\n', 1
)
settings = paths(workspace[workspace.index("[workspace.dependencies]"):], source)
# The CLI has no dependency on this runtime; don't resolve its unused Git patch.
settings = re.sub(r'^v8 = \{ git = [^\n]+\n', '', settings, flags=re.MULTILINE)
manifest = '''# Generated by ../generate_native_manifest.py from the pinned Codex CLI.
[package]
name = "athenaeum-agent"
version = "0.1.0"
edition = "2024"
license = "Apache-2.0"
build = "../codex/codex-rs/cli/build.rs"

[workspace]
resolver = "2"

[[bin]]
name = "athenaeum-agent"
path = "src/main.rs"

'''+dependencies+"\n"+settings
native.mkdir(exist_ok=True)
(native / "Cargo.toml").write_text(manifest, encoding="utf-8", newline="\n")
(native / "src").mkdir(exist_ok=True)
(native / "src" / "main.rs").write_text(
    '// Compile the imported CLI and its production runtime in-process.\n'
    'include!("../../codex/codex-rs/cli/src/main.rs");\n', encoding="utf-8", newline="\n"
)
(native / ".cargo").mkdir(exist_ok=True)
(native / ".cargo" / "config.toml").write_bytes((source / ".cargo" / "config.toml").read_bytes())
lock = native / "Cargo.lock"
if not lock.exists():
    lock.write_bytes((source / "Cargo.lock").read_bytes())
print("Derived native CLI workspace from upstream production dependencies (no V8 host)")
